"""Run the BANK-001 benchmarks on the prepared Stage 2 validation CSV.

Jupyter: %run Bank_Marketing_Stage2_Benchmarks.py stage2_data/validation.csv
The script prints the results and saves validation_benchmarks.json beside the CSV.
"""

import argparse
import csv
import json
import random
from pathlib import Path

SELECTION_COUNT = 1647
PRIOR_SUCCESS_SEED = 42
VALIDATION_IDS = range(24713, 32951)


def read_validation(path):
    """Read only the approved validation records, in source order."""
    with path.open(encoding="utf-8-sig", newline="") as stream:
        reader = csv.DictReader(stream)
        required = {"source_row_id", "poutcome", "y"}
        if not required.issubset(reader.fieldnames or []):
            raise ValueError("Use validation.csv generated by the Stage 2 setup script.")
        rows = list(reader)

    if [int(row["source_row_id"]) for row in rows] != list(VALIDATION_IDS):
        raise ValueError("Expected validation source rows 24,713 through 32,950 in order.")
    if any(row["y"] not in ("yes", "no") for row in rows):
        raise ValueError("Expected yes or no outcomes in validation.csv.")
    if any(row["poutcome"] not in ("success", "failure", "nonexistent") for row in rows):
        raise ValueError("Unexpected prior campaign outcome in validation.csv.")
    return rows


def prior_success_selection(rows, count):
    """Select by prior outcome, with uniform seeded sampling for ties."""
    prior_success = [row for row in rows if row["poutcome"] == "success"]
    others = [row for row in rows if row["poutcome"] != "success"]
    rng = random.Random(PRIOR_SUCCESS_SEED)
    if len(prior_success) > count:
        return rng.sample(prior_success, count)
    return prior_success + rng.sample(others, count - len(prior_success))


def metrics(subscribers, selections, total_subscribers):
    return {
        "selections": selections,
        "subscribers": subscribers,
        "selected_subscription_rate": subscribers / selections,
        "subscriber_capture_rate": subscribers / total_subscribers,
    }


def run(path):
    rows = read_validation(path)
    total_subscribers = sum(row["y"] == "yes" for row in rows)
    if total_subscribers != 912:
        raise ValueError("Validation subscriber count differs from the approved intake count.")

    selected = prior_success_selection(rows, SELECTION_COUNT)
    historical_subscribers = sum(row["y"] == "yes" for row in selected)
    prior_success_records = sum(row["poutcome"] == "success" for row in selected)
    expected_subscribers = SELECTION_COUNT * total_subscribers / len(rows)

    results = {
        "block": "validation",
        "records": len(rows),
        "total_subscribers": total_subscribers,
        "random_selection_expected": metrics(
            expected_subscribers, SELECTION_COUNT, total_subscribers
        ),
        "prior_campaign_success_observed": {
            **metrics(historical_subscribers, len(selected), total_subscribers),
            "prior_success_records": prior_success_records,
            "random_fill_records": len(selected) - prior_success_records,
            "sampling_seed": PRIOR_SUCCESS_SEED,
            "sampling_method": "Python random.Random.sample without replacement in source order",
            "selected_source_row_ids": [int(row["source_row_id"]) for row in selected],
        },
    }
    output = path.with_name("validation_benchmarks.json")
    output.write_text(json.dumps(results, indent=2) + "\n", encoding="utf-8")
    for name in ("random_selection_expected", "prior_campaign_success_observed"):
        result = results[name]
        print(
            f"{name}: {result['subscribers']:.2f} subscribers, "
            f"{result['selected_subscription_rate']:.2%} selected subscription rate, "
            f"{result['subscriber_capture_rate']:.2%} subscriber capture"
        )
    print(f"Saved {output}")


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("validation_csv", type=Path)
    run(parser.parse_args().validation_csv)
